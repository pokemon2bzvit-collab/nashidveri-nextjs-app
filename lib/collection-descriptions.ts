export function getCollectionDescription(brand: string, collection: string, category: Category) {
  return descriptions[`${brand}::${collection}`]
    || (category === "entrance"
      ? "Моделі, декори та комплектації для квартири або приватного будинку."
      : "Моделі, декори й доступні варіанти виконання для вашого інтер’єру.");
}

export function getCollectionIntroduction(brand: string, collection: string, category: Category) {
  return introductions[`${brand}::${collection}`]
    || `${getCollectionDescription(brand, collection, category)} Підкажемо доступні декори, комплектацію та актуальну ціну.`;
}
