-- Не вигадує параметри: використовує лише фабрику, назву моделі, категорію та колекцію з каталогу.

-- Міжкімнатні двері Термінус.
update public.products
set description = 'Міжкімнатні двері «' || name || '» від фабрики Термінус, колекція «' || collection || '». Допоможемо підібрати декор, розмір полотна, короб і фурнітуру під ваш інтер’єр.'
where brand = 'Термінус'
  and description ilike '%характеристики та актуальну ціну уточнюйте у менеджера%';

